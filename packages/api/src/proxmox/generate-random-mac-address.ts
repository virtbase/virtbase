export function generateRandomMacAddress(): string {
  // Default prefix for Proxmox VMs
  return `BC:24:11:XX:XX:XX`.replace(/X/g, () =>
    "0123456789ABCDEF".charAt(Math.floor(Math.random() * 16)),
  );
}
